/**
 * Relative date tokens in the seed ("-3d", "-0d08h") are resolved against the
 * current clock so the demo always looks freshly used.
 */
function resolveRelative(token: string | null, now: Date): string | null {
  if (!token) return null;
  const match = /^-(?:(\d+)d)?(?:(\d+)h)?$/.exec(token);
  if (!match) return token;
  const days = Number(match[1] ?? 0);
  const hours = Number(match[2] ?? 0);
  const date = new Date(now);
  date.setDate(date.getDate() - days);
  date.setHours(date.getHours() - hours);
  return date.toISOString();
}

