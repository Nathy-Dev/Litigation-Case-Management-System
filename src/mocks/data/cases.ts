function daysAgo(now: Date, days: number): string {
  const date = new Date(now);
  date.setDate(date.getDate() - days);
  return date.toISOString();
}

/** Short ref → generated case id, so related-case links resolve. */
export const CASE_ID_BY_REF: Record<string, string> = Object.fromEntries(
  seeds.map((seed, index) => [seed.ref, `case_${String(index + 1).padStart(3, '0')}`]),
);

export function buildCases(now: Date): CaseRecord[] {
  const year = now.getFullYear();

  return seeds.map((seed, index) => {
    const id = CASE_ID_BY_REF[seed.ref]!;
    const createdDays = seed.createdDaysAgo ?? (seed.filedDaysAgo ?? 0) + 14;
    const filedYear = seed.filedDaysAgo
      ? new Date(daysAgo(now, seed.filedDaysAgo)).getFullYear()
      : year;

    return {
      id,
      caseId: `HYP/LCMS/${filedYear}/${String(index + 1).padStart(4, '0')}`,
      caseReference: seed.caseReference ?? null,
      title: seed.title,
      suitNumber: seed.suitNumber,
      courtId: seed.courtId,
      caseTypeId: seed.caseTypeId,
      status: seed.status,
      priority: seed.priority,
      filingDate: seed.filedDaysAgo === null ? null : daysAgo(now, seed.filedDaysAgo),
      claimValue: seed.claimValue,
      matterOwnerId: seed.ownerId,
      assigneeIds: seed.assignees,
      externalCounselIds: seed.counsel,
      teamId: seed.teamId,
      parties: seed.parties.map((party, partyIndex) => ({
        id: `${id}_party_${partyIndex + 1}`,
        name: party.name,
        role: party.role,
        type: party.type,
        email: party.email ?? null,
        phone: party.phone ?? null,
        address: party.address ?? null,
        representedBy: party.representedBy ?? null,
      })),
      relatedCases: (seed.related ?? [])
        .filter((link) => CASE_ID_BY_REF[link.ref])
        .map((link) => ({
          caseId: CASE_ID_BY_REF[link.ref]!,
          linkType: link.linkType,
          note: link.note,
        })),
      tags: seed.tags,
      confidential: seed.confidential ?? false,
      restrictedToUserIds: seed.restrictedTo ?? [],
      summary: seed.summary,
      reliefSought: seed.relief,
      presidingJudge: seed.judge,
      createdById: seed.ownerId,
      createdAt: daysAgo(now, createdDays),
      updatedAt: daysAgo(now, Math.max(0, Math.round((index % 9) + 1))),
      archivedAt: seed.archivedDaysAgo ? daysAgo(now, seed.archivedDaysAgo) : null,
    } satisfies CaseRecord;
  });
}
